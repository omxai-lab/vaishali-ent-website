        buildSummaryText: function () {
            var sorted = this.sortedNewestFirst();
            var last10 = sorted.slice(0, 10);

            var total = this.entries.length;
            var thirtyDaysAgo = new Date();
            thirtyDaysAgo.setDate(thirtyDaysAgo.getDate() - 30);
            var last30 = this.entries.filter(function (e) {
                var d = new Date(e.dateTime);
                return !isNaN(d.getTime()) && d.getTime() >= thirtyDaysAgo.getTime();
            }).length;

            var triggerCounts = {};
            var sensationCounts = {};
            this.entries.forEach(function (e) {
                (e.triggers || []).forEach(function (t) {
                    triggerCounts[t] = (triggerCounts[t] || 0) + 1;
                });
                if (e.sensation) sensationCounts[e.sensation] = (sensationCounts[e.sensation] || 0) + 1;
            });
            function topKey(counts) {
                var bestKey = null;
                var bestCount = 0;
                Object.keys(counts).forEach(function (k) {
                    if (counts[k] > bestCount) {
                        bestCount = counts[k];
                        bestKey = k;
                    }
                });
                return bestKey;
            }
            var topTrigger = topKey(triggerCounts);
            var topSensation = topKey(sensationCounts);

            var lines = [];
            lines.push("VERTIGO EPISODE DIARY SUMMARY");
            lines.push("Dr. Vaishali Sangole's ENT & Vertigo Clinic");
            lines.push("");
            lines.push("Total episodes logged: " + total);
            lines.push("Episodes in last 30 days: " + last30);
            lines.push("Most common trigger: " + (topTrigger ? (TRIGGER_LABELS[topTrigger] || topTrigger) : "N/A"));
            lines.push("Most common sensation: " + (topSensation ? (SENSATION_LABELS[topSensation] || topSensation) : "N/A"));
            lines.push("");
            lines.push("Last " + last10.length + " episode(s):");

            last10.forEach(function (entry, idx) {
                lines.push("");
                lines.push((idx + 1) + ". " + formatDateDisplay(entry.dateTime));
                lines.push("   Duration: " + (DURATION_LABELS[entry.duration] || entry.duration));
                lines.push("   Sensation: " + (SENSATION_LABELS[entry.sensation] || entry.sensation));
                lines.push("   Severity: " + entry.severity + "/5");
                if (entry.triggers && entry.triggers.length > 0) {
                    var trigText = entry.triggers.map(function (t) {
                        if (t === "other" && entry.otherTriggerText) {
                            return "Other (" + entry.otherTriggerText + ")";
                        }
                        return TRIGGER_LABELS[t] || t;
                    }).join(", ");
                    lines.push("   Triggers: " + trigText);
                }
                if (entry.symptoms && entry.symptoms.length > 0) {
                    var sympText = entry.symptoms.map(function (s) { return SYMPTOM_LABELS[s] || s; }).join(", ");
                    lines.push("   Symptoms: " + sympText);
                }
                if (entry.notes) {
                    lines.push("   Notes: " + entry.notes);
                }
            });

            if (last10.length === 0) {
                lines.push("(No episodes logged yet.)");
            }

            return lines.join("\n");
        },

