        copyAsText: function () {
            var text = this.buildSummaryText();
            var feedbackEl = document.getElementById("diary-copy-feedback");

            function showFeedback() {
                if (!feedbackEl) return;
                feedbackEl.classList.add("active");
                window.setTimeout(function () {
                    feedbackEl.classList.remove("active");
                }, 2000);
            }

            if (navigator.clipboard && navigator.clipboard.writeText) {
                navigator.clipboard.writeText(text).then(showFeedback, function () {
                    diary.fallbackCopy(text, showFeedback);
                });
            } else {
                this.fallbackCopy(text, showFeedback);
            }
        },

        fallbackCopy: function (text, cb) {
            var textarea = document.getElementById("diary-copy-fallback");
            if (!textarea) return;
            textarea.value = text;
            textarea.style.position = "fixed";
            textarea.style.left = "-9999px";
            textarea.focus();
            textarea.select();
            try {
                document.execCommand("copy");
                if (cb) cb();
            } catch (e) {
                // Silently ignore; user can manually select the textarea contents if needed.
            }
        }
    };

