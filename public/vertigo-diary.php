<script>
(function () {
    "use strict";

    var STORAGE_KEY = "vertigo-diary-v1";

    var DURATION_LABELS = {
        seconds: "Seconds",
        lt1min: "Less than 1 minute",
        "1to10min": "1 – 10 minutes",
        "10to60min": "10 – 60 minutes",
        hours: "Hours",
        allday: "All day"
    };

    var SENSATION_LABELS = {
        spinning: "Spinning",
        imbalance: "Imbalance",
        lightheaded: "Lightheaded",
        fainting: "Fainting"
    };

    var TRIGGER_LABELS = {
        turning_bed: "Turning in bed",
        looking_updown: "Looking up/down",
        standing_up: "Standing up",
        stress: "Stress",
        loud_sounds: "Loud sounds",
        none_noticed: "None noticed",
        other: "Other"
    };

    var SYMPTOM_LABELS = {
        nausea_vomiting: "Nausea/vomiting",
        ear_fullness: "Ear fullness",
        ringing: "Ringing",
        hearing_change: "Hearing change",
        headache_migraine: "Headache/migraine",
        sweating: "Sweating",
        none: "None"
    };

    // -----------------------------------------------------------------
    // Storage availability check (handles Private/Incognito mode)
    // -----------------------------------------------------------------
    function storageAvailable() {
        try {
            var testKey = "__vertigo_diary_test__";
            window.localStorage.setItem(testKey, "1");
            window.localStorage.removeItem(testKey);
            return true;
        } catch (e) {
            return false;
        }
    }

    var hasStorage = storageAvailable();

    function loadEntries() {
        if (!hasStorage) return [];
        try {
            var raw = window.localStorage.getItem(STORAGE_KEY);
            if (!raw) return [];
            var parsed = JSON.parse(raw);
            if (!Array.isArray(parsed)) return [];
            return parsed;
        } catch (e) {
            return [];
        }
    }

    function saveEntries(entries) {
        if (!hasStorage) return;
        try {
            window.localStorage.setItem(STORAGE_KEY, JSON.stringify(entries));
        } catch (e) {
            // ignore quota errors silently; storage warning already shown if unavailable
        }
    }

    function uid() {
        return Date.now().toString(36) + "-" + Math.random().toString(36).slice(2, 9);
    }

    function pad2(n) { return n < 10 ? "0" + n : "" + n; }

    function defaultDateTimeLocalValue() {
        var d = new Date();
        return d.getFullYear() + "-" + pad2(d.getMonth() + 1) + "-" + pad2(d.getDate()) +
            "T" + pad2(d.getHours()) + ":" + pad2(d.getMinutes());
    }

    function formatDateDisplay(isoLike) {
        var d = new Date(isoLike);
        if (isNaN(d.getTime())) return isoLike;
        var options = { day: "2-digit", month: "short", year: "numeric", hour: "2-digit", minute: "2-digit" };
        return d.toLocaleString("en-IN", options);
    }

    var diary = {
        entries: [],

        init: function () {
            this.entries = loadEntries();

            var warningEl = document.getElementById("diary-storage-warning");
            var appEl = document.getElementById("diary-app");
            if (!hasStorage) {
                if (warningEl) warningEl.classList.add("active");
                if (appEl) appEl.style.display = "none";
                return;
            }

            var dateInput = document.getElementById("diary-input-date");
            if (dateInput) dateInput.value = defaultDateTimeLocalValue();

            var severityInput = document.getElementById("diary-input-severity");
            var severityLabel = document.getElementById("diary-severity-label");
            var severityBadge = document.getElementById("diary-severity-badge");
            if (severityInput) {
                severityInput.addEventListener("input", function () {
                    if (severityLabel) severityLabel.textContent = severityInput.value;
                    if (severityBadge) severityBadge.textContent = severityInput.value;
                });
            }

            var otherCheck = document.getElementById("diary-trigger-other-check");
            var otherText = document.getElementById("diary-trigger-other-text");
            if (otherCheck && otherText) {
                otherCheck.addEventListener("change", function () {
                    otherText.style.display = otherCheck.checked ? "block" : "none";
                    if (!otherCheck.checked) otherText.value = "";
                });
            }

            var form = document.getElementById("diary-entry-form");
            if (form) form.addEventListener("submit", this.handleSubmit.bind(this));

            var clearAllBtn = document.getElementById("diary-clear-all-btn");
            if (clearAllBtn) clearAllBtn.addEventListener("click", this.clearAll.bind(this));

            var whatsappBtn = document.getElementById("diary-whatsapp-btn");
            if (whatsappBtn) whatsappBtn.addEventListener("click", this.shareWhatsApp.bind(this));

            var copyBtn = document.getElementById("diary-copy-btn");
            if (copyBtn) copyBtn.addEventListener("click", this.copyAsText.bind(this));

            this.render();
        },

        handleSubmit: function (evt) {
            evt.preventDefault();

            var dateVal = document.getElementById("diary-input-date").value;
            var durationVal = document.getElementById("diary-input-duration").value;
            var sensationVal = document.getElementById("diary-input-sensation").value;
            var severityVal = document.getElementById("diary-input-severity").value;
            var notesVal = document.getElementById("diary-input-notes").value;

            if (!dateVal || !durationVal || !sensationVal) {
                return;
            }

            var triggerChecks = document.querySelectorAll("#diary-trigger-checks input[type='checkbox']:checked");
            var triggers = [];
            triggerChecks.forEach(function (cb) { triggers.push(cb.value); });

            var otherTriggerText = "";
            var otherTextEl = document.getElementById("diary-trigger-other-text");
            if (triggers.indexOf("other") !== -1 && otherTextEl) {
                otherTriggerText = otherTextEl.value.trim().slice(0, 200);
            }

            var symptomChecks = document.querySelectorAll("#diary-symptom-checks input[type='checkbox']:checked");
            var symptoms = [];
            symptomChecks.forEach(function (cb) { symptoms.push(cb.value); });

            var entry = {
                id: uid(),
                dateTime: dateVal,
                duration: durationVal,
                sensation: sensationVal,
                triggers: triggers,
                otherTriggerText: otherTriggerText,
                symptoms: symptoms,
                severity: parseInt(severityVal, 10) || 3,
                notes: (notesVal || "").trim().slice(0, 1000),
                createdAt: new Date().toISOString()
            };

            this.entries.push(entry);
            saveEntries(this.entries);
            this.render();

            var form = document.getElementById("diary-entry-form");
            if (form) form.reset();

            var dateInput = document.getElementById("diary-input-date");
            if (dateInput) dateInput.value = defaultDateTimeLocalValue();

            var severityInput = document.getElementById("diary-input-severity");
            var severityLabel = document.getElementById("diary-severity-label");
            var severityBadge = document.getElementById("diary-severity-badge");
            if (severityInput) severityInput.value = 3;
            if (severityLabel) severityLabel.textContent = "3";
            if (severityBadge) severityBadge.textContent = "3";

            var otherTextEl2 = document.getElementById("diary-trigger-other-text");
            if (otherTextEl2) otherTextEl2.style.display = "none";
        },

        deleteEntry: function (id) {
            this.entries = this.entries.filter(function (e) { return e.id !== id; });
            saveEntries(this.entries);
            this.render();
        },

        clearAll: function () {
            if (this.entries.length === 0) return;
            var confirmed = window.confirm("Delete all diary entries from this device? This cannot be undone.");
            if (!confirmed) return;
            this.entries = [];
            saveEntries(this.entries);
            this.render();
        },

        sortedNewestFirst: function () {
            return this.entries.slice().sort(function (a, b) {
                return new Date(b.dateTime).getTime() - new Date(a.dateTime).getTime();
            });
        },

        render: function () {
            this.renderSummary();
            this.renderList();
        },

        renderSummary: function () {
            var total = this.entries.length;

            var thirtyDaysAgo = new Date();
            thirtyDaysAgo.setDate(thirtyDaysAgo.getDate() - 30);
            var last30 = this.entries.filter(function (e) {
                var d = new Date(e.dateTime);
                return !isNaN(d.getTime()) && d.getTime() >= thirtyDaysAgo.getTime();
            }).length;

            var triggerCounts = {};
            var sensationCounts = {};
            this.entries.forEach(function (e) {
                (e.triggers || []).forEach(function (t) {
                    triggerCounts[t] = (triggerCounts[t] || 0) + 1;
                });
                if (e.sensation) sensationCounts[e.sensation] = (sensationCounts[e.sensation] || 0) + 1;
            });

            function topKey(counts) {
                var bestKey = null;
                var bestCount = 0;
                Object.keys(counts).forEach(function (k) {
                    if (counts[k] > bestCount) {
                        bestCount = counts[k];
                        bestKey = k;
                    }
                });
                return bestKey;
            }

            var topTrigger = topKey(triggerCounts);
            var topSensation = topKey(sensationCounts);

            var totalEl = document.getElementById("diary-stat-total");
            var last30El = document.getElementById("diary-stat-30days");
            var triggerEl = document.getElementById("diary-stat-trigger");
            var sensationEl = document.getElementById("diary-stat-sensation");

            if (totalEl) totalEl.textContent = String(total);
            if (last30El) last30El.textContent = String(last30);
            if (triggerEl) triggerEl.textContent = topTrigger ? (TRIGGER_LABELS[topTrigger] || topTrigger) : "—";
            if (sensationEl) sensationEl.textContent = topSensation ? (SENSATION_LABELS[topSensation] || topSensation) : "—";
        },

        renderList: function () {
            var self = this;
            var listEl = document.getElementById("diary-episode-list");
            if (!listEl) return;

            listEl.textContent = "";

            var sorted = this.sortedNewestFirst();

            if (sorted.length === 0) {
                var empty = document.createElement("div");
                empty.className = "diary-empty-state";
                empty.textContent = "No episodes logged yet. Use the form above to record your first entry.";
                listEl.appendChild(empty);
                return;
            }

            sorted.forEach(function (entry) {
                var card = document.createElement("div");
                card.className = "diary-episode-card";

                var main = document.createElement("div");
                main.className = "diary-episode-main";

                var dateDiv = document.createElement("div");
                dateDiv.className = "diary-episode-date";
                dateDiv.textContent = formatDateDisplay(entry.dateTime);
                main.appendChild(dateDiv);

                var metaDiv = document.createElement("div");
                metaDiv.className = "diary-episode-meta";

                var durationSpan = document.createElement("span");
                durationSpan.textContent = DURATION_LABELS[entry.duration] || entry.duration;
                metaDiv.appendChild(durationSpan);

