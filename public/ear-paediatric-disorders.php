                                    <h6>5. How can I prevent ear infections?</h6>

                                    <p><b>Non-medical Methods</b><br>

                                        Breastfeeding your infant is associated with less middle-ear infections than bottle-feeding. No smoking in the household as passive smoke is associated with increased risk of middle-ear infections. Pacifier use is associated with ear infections and is discouraged after the age of one year. Daycare is a risk factor for middle-ear infections, as the babies pass colds around to the other children and colds are associated with the middle-ear disease.</p>

                                </div>

