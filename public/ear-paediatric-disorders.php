                                    <h6>2. What are the signs and symptoms of the middle-ear disease?</h6>

                                    <p><b>Acute Middle-Ear Infection (Acute Otitis Media)</b><br>

                                        Acute middle-ear infection is the rapid onset of an earache (otalgia) usually with fever and often with hearing loss. In young babies who are not verbal, the earache may show as tugging at the ear, crying and fever is usually present. Also, there may be systemic signs and symptoms associated with the above, such as irritability, sleepiness (lethargy), not wanting to eat (anorexia), vomiting, and diarrhea. In some attacks, the eardrum may rupture which results in drainage from the ear canal that looks like pus that comes out of the nose during a cold. There may be blood in the discharge.</p>

                                </div>

