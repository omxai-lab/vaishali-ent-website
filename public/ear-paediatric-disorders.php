                                    <p><b>Middle-Ear Effusion (Otitis Media with Effusion)</b><br>

                                        Otitis media with effusion is the occurrence of fluid in the middle ear that is not infected and typically without symptoms. It can occur following an attack of acute middle-ear infection in which the signs and symptoms of acute infection have resolved, with or without antibiotic treatment, in which case it is called persistent middle-ear effusion (fluid). Or it may occur without any previous episode of acute otitis media. The child may complain of fullness (mild pain) in the ear and hearing loss, which may be only evident to parents and teachers, or suspected when the television is very loud. Some children will constantly ask to have words repeated with “what?” The hearing loss may be identified by a routine school screening hearing test or tests performed during visits to the primary care physician. Some children complain of hearing noises (tinnitus) in their ears, which may be noted as ringing, buzzing, snapping or popping. Although somewhat uncommon, a middle-ear disease may cause balance problems (vertigo) in children and adults. Adults and older children will be very specific about imbalance, but in infants, the parents will relate the child has become “clumsy,” such as falling while attempting to walk despite successfully walking in the past.</p>

                                    <p><b>Eustachian Tube Dysfunction</b><br>

                                        The Eustachian tube connects the back of the nose (nasopharynx) to the middle ear which equalizes air pressure between the outside pressure and the pressure in the middle ear. (Figure 4-2 from Targeted Therapies. A caption should be: “Eustachian tube connects the nasopharynx with the middle ear.”) Some older children and adults who have problems in opening their Eustachian tube during periods of colds or allergy, during descent in airplanes, or even on a chronic basis will complain of mild ear pain or fullness and tinnitus. This disorder may occur in girls in puberty.</p>

