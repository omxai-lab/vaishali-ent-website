                                        Vaccines are effective in preventing most but not all, middle-ear infections, such as the ones against the bacterium pneumococci. Influenza virus vaccines are an option in an effort to prevent recurrent episodes. Antibiotic Prophylaxis (prevention), such as a low dose of amoxicillin given at bedtime, is effective. But this method when given long-term has been associated with drug-resistant bacteria. Note: Decisions related to administering vaccines and antibiotics for prevention, should be between the physician and the parent, i.e., shared decision making.</p>

                                    <p><b>Surgical Methods</b><br>

                                        Myringotomy and tympanostomy tube is a surgical option for prevention of middle-ear infections. The operation requires a very short general anesthetic as an outpatient procedure. The otolaryngologist will insert a tiny plastic tube in the eardrum which aerates the middle ear to relieve fluid in the middle ear and prevent further middle-ear disease. (See above FAQ (Frequently Asked Questions): “How is the middle ear examined, and what does the eardrum look like when diseased?” for a photograph of a tube in the eardrum.) Note: Decisions related to recommending this surgical procedure for prevention of otitis media should be between the physician and the patient or parents of children, i.e., shared decision making.</p>

