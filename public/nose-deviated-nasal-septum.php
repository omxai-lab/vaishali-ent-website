                                <div class="ser-info-wrap">
                                    <h6>What are the investigations required for confirming the diagnosis of deviated nasal septum?</h6>
                                    <p>Investigations for deviated nasal septum include:</p>
                                    <ul class="list-group-borderless">
                                        <li><i class="fa fa-check"></i> X-ray paranasal sinuses, Waters view and Caldwells view gives an idea of posterior deviation if any and status of the sinuses</li>
                                        <li><i class="fa fa-check"></i> CT Scan paranasal sinuses (PNS) with the Axial and coronal sections</li>
                                        <li><i class="fa fa-check"></i> Shows the severity of sinusitis</li>
                                        <li><i class="fa fa-check"></i> Any complications involving the orbit or optic nerve</li>
                                        <li><i class="fa fa-check"></i> Diagnose sphenoidal sinusitis</li>
                                    </ul>
                                </div>
                                <div class="ser-info-wrap full">
                                    <h6>What is the treatment for deviated nasal septum?</h6>
                                    <p>Depending on the severity of the symptoms and age, the patient is advised any of the following for deviated nasal septum:</p>
                                    <ul class="list-group-borderless">
                                        <li><i class="fa fa-check"></i> SMR (Sub Mucous Resection) surgery</li>
                                        <li><i class="fa fa-check"></i> Septoplasty Surgery.This is the more commonly done surgery</li>
                                    </ul>
                                    <p>The above surgery is often combined with Functional Endoscopic Sinus Surgery if there is moderate to severe disease in the sinuses.</p>
