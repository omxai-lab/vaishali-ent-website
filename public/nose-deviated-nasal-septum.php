                                    <h6>Introduction</h6>
                                    <p>It is the deviation of the nasal bone dividing the nose into two nostrils to one side. Hence the patient may have recurrent blockage of one nostril. Septal deviations, though common, require being treated only if they produce symptoms affecting nasal function.</p>

                                </div>
                                <div class="ser-info-wrap full">
                                    <h6>What are the causes of deviated nasal septum?</h6>

                                    <ul class="list-group-borderless">
                                        <li><i class="fa fa-check"></i> Birth Moulding theory: Abnormal intrauterine posture and second stage of labor lasting more than 15 minutes in primipara.However, these are postulated theories.</li>
                                        <li><i class="fa fa-check"></i> Trauma: Commonest cause of the deviation</li>
                                        <li><i class="fa fa-check"></i> Secondary to a tumor, mass or polyps in the nose to compression.</li>
                                        <li><i class="fa fa-check"></i> Developmental Buckling: If the septum starts growing rapidly it gets buckled to one side to accommodate itself.</li>
                                    </ul>
                                </div>
                            </li>
                            <li class="sec-item">
                                <div class="ser-img-wrap">
                                    <img src="images/nasal2.jpg" class="img-fluid" alt="">
                                </div>
                                <div class="ser-info-wrap">
                                    <h6>What are the types of Septal deviation?</h6>

                                    <ul class="list-group-borderless">
                                        <li><i class="fa fa-check"></i> The deviation can be C shaped, S-shaped high or low deviation.</li>
                                        <li><i class="fa fa-check"></i> Dislocation: The anterior end of the lower border of septum gets displaced to one side.</li>
                                        <li><i class="fa fa-check"></i> Septal spurs: They are seen at the. cartilage-bony junction of the septum.</li>
                                        <li><i class="fa fa-check"></i> Thickened septum post trauma</li>
                                    </ul>
                                </div>
                                <div class="ser-info-wrap full">
                                    <h6>What are the symptoms of deviated nasal septum?</h6>
                                    <p>Common symptoms of the deviated nasal septum are:</p>
                                    <ul class="list-group-borderless">
                                        <li><i class="fa fa-check"></i> Nasal blockage</li>
                                        <li><i class="fa fa-check"></i> A headache due to</li>
                                        <li><i class="fa fa-check"></i> Sinusitis with a vacuum headache</li>
                                        <li><i class="fa fa-check"></i> Neuralgia</li>
                                        <li><i class="fa fa-check"></i> Epistaxis</li>
                                        <li><i class="fa fa-check"></i> Anosmia</li>
                                    </ul>
                                    <h6>What are the common signs seen on examination of deviated nasal septum?</h6>
                                    <p>Common signs of deviated nasal septum:</p>
                                    <ul class="list-group-borderless">
                                        <li><i class="fa fa-check"></i> External deformity of the nose</li>
                                        <li><i class="fa fa-check"></i> Anterior rhinoscopy reveals deviation of the nasal septum.</li>
                                        <li><i class="fa fa-check"></i> Cottle’s test: Pulling the cheek outward and upward causes opening of internal nares and relieves the blockage.</li>
                                    </ul>
                                </div>
                            </li>
                            <li class="sec-item">
                                <div class="ser-img-wrap">
