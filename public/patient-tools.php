    // ---------------------------------------------------------------
    // TINNITUS SOUND MASKER (Web Audio API)
    // ---------------------------------------------------------------
    var tinnitusMasker = {
        audioCtx: null,
        source: null,
        gainNode: null,
        isPlaying: false,
        currentType: "white",
        volume: 0.5,
        noiseBuffers: {}, // cache: created once per type, reused on every play

        init: function () {
            this.setupListeners();
        },

        setupListeners: function () {
            var self = this;
            var playBtn = document.getElementById("tinnitus-play-btn");
            var volSlider = document.getElementById("tinnitus-volume");
            var volTxt = document.getElementById("vol-txt");

            if (playBtn) {
                playBtn.addEventListener("click", function () { self.togglePlayback(); });
            }

            if (volSlider) {
                volSlider.addEventListener("input", function (e) {
                    var val = e.target.value;
                    self.volume = val / 100;
                    if (volTxt) volTxt.innerText = val + "%";
                    if (self.gainNode && self.audioCtx) {
                        self.gainNode.gain.setValueAtTime(self.volume, self.audioCtx.currentTime);
                    }
                });
            }

            ["noise-white", "noise-pink", "noise-brown"].forEach(function (id) {
                var el = document.getElementById(id);
                if (el) {
                    el.addEventListener("click", function () {
                        document.querySelectorAll("#tool-pane-tinnitus .grid-select-card").forEach(function (c) {
                            c.classList.remove("selected");
                        });
                        el.classList.add("selected");

                        var type = el.getAttribute("data-type");
                        self.currentType = type;

                        if (self.isPlaying) {
                            self.stopSound();
                            self.startSound();
                        }
                    });
                }
            });
        },

        togglePlayback: function () {
            if (this.isPlaying) {
                this.stopSound();
            } else {
                this.startSound();
            }
        },

        hideFallback: function () {
            var msg = document.getElementById("audio-fallback-msg");
            if (msg) msg.classList.remove("active");
        },

        showFallback: function () {
            var msg = document.getElementById("audio-fallback-msg");
            if (msg) msg.classList.add("active");
        },

        startSound: function () {
            var self = this;
            try {
                if (!this.audioCtx) {
                    var AudioContextCtor = window.AudioContext || window.webkitAudioContext;
                    if (!AudioContextCtor) {
                        throw new Error("Web Audio API not supported in this browser.");
                    }
                    this.audioCtx = new AudioContextCtor();
                }

                var proceedWithPlayback = function () {
                    try {
                        var buffer = self.getNoiseBuffer(self.currentType);

                        self.source = self.audioCtx.createBufferSource();
                        self.source.buffer = buffer;
                        self.source.loop = true;

                        self.gainNode = self.audioCtx.createGain();
                        self.gainNode.gain.setValueAtTime(self.volume, self.audioCtx.currentTime);

                        self.source.connect(self.gainNode);
                        self.gainNode.connect(self.audioCtx.destination);

                        self.source.start(0);
                        self.isPlaying = true;
                        self.hideFallback();

                        var playBtn = document.getElementById("tinnitus-play-btn");
                        if (playBtn) {
                            playBtn.innerHTML = '<i class="fas fa-pause"></i> Stop Sound Generator';
                            playBtn.classList.remove("btn-primary-tool");
                            playBtn.classList.add("btn-accent-tool");
                        }
                    } catch (innerErr) {
                        console.error("Tinnitus masker playback failed: ", innerErr);
                        self.showFallback();
                    }
                };

                if (this.audioCtx.state === "suspended") {
                    this.audioCtx.resume().then(proceedWithPlayback).catch(function (err) {
                        console.error("AudioContext resume failed: ", err);
                        self.showFallback();
                    });
                } else {
                    proceedWithPlayback();
                }
            } catch (e) {
                console.error("Audio Context failed: ", e);
                this.showFallback();
            }
        },

        stopSound: function () {
            if (this.source) {
                try {
                    this.source.stop();
                } catch (e) {
                    // Ignore errors from stopping an already-stopped source.
                }
                try {
                    this.source.disconnect();
                } catch (e) {
                    // Ignore disconnect errors.
                }
                this.source = null;
            }
            this.isPlaying = false;

            var playBtn = document.getElementById("tinnitus-play-btn");
            if (playBtn) {
                playBtn.innerHTML = '<i class="fas fa-play"></i> Start Sound Generator';
                playBtn.classList.remove("btn-accent-tool");
                playBtn.classList.add("btn-primary-tool");
            }
        },

        // Buffers are created once per noise type and cached, then reused for every
        // play. Capped at 2 seconds at a maximum of 48kHz, regardless of the actual
        // device sample rate, to bound memory usage.
        getNoiseBuffer: function (type) {
            if (this.noiseBuffers[type]) {
                return this.noiseBuffers[type];
            }
            var buffer = this.createNoiseBuffer(type);
            this.noiseBuffers[type] = buffer;
            return buffer;
        },

        createNoiseBuffer: function (type) {
            var deviceSampleRate = this.audioCtx.sampleRate;
            var cappedSampleRate = Math.min(deviceSampleRate, 48000);
            var durationSeconds = 2;
            var bufferSize = durationSeconds * cappedSampleRate;

            // AudioBuffer must be created using the context's actual sample rate,
            // but we still cap the number of frames (bufferSize) to bound memory to
            // a maximum of 2 seconds @ 48kHz worth of samples.
            var maxFrames = durationSeconds * 48000;
            if (bufferSize > maxFrames) bufferSize = maxFrames;

            var buffer = this.audioCtx.createBuffer(1, bufferSize, deviceSampleRate);
            var data = buffer.getChannelData(0);

            if (type === "white") {
                for (var i = 0; i < bufferSize; i++) {
                    data[i] = Math.random() * 2 - 1;
                }
            } else if (type === "pink") {
                var b0 = 0, b1 = 0, b2 = 0, b3 = 0, b4 = 0, b5 = 0, b6 = 0;
                for (var j = 0; j < bufferSize; j++) {
                    var white = Math.random() * 2 - 1;
                    b0 = 0.99886 * b0 + white * 0.0555179;
                    b1 = 0.99332 * b1 + white * 0.0750759;
                    b2 = 0.96900 * b2 + white * 0.1538520;
                    b3 = 0.86650 * b3 + white * 0.3104856;
                    b4 = 0.55000 * b4 + white * 0.5329522;
                    b5 = -0.7616 * b5 - white * 0.0168980;
                    data[j] = b0 + b1 + b2 + b3 + b4 + b5 + b6 + white * 0.5362;
                    data[j] *= 0.11;
                    b6 = white * 0.115926;
                }
            } else if (type === "brown") {
                var lastOut = 0.0;
                for (var k = 0; k < bufferSize; k++) {
                    var w = Math.random() * 2 - 1;
                    data[k] = (lastOut + (0.02 * w)) / 1.02;
                    lastOut = data[k];
                    data[k] *= 3.5;
                }
            }
            return buffer;
        }
