        <!-- ============ CAWTHORNE-COOKSEY ============ -->
        <div class="exercise-card" id="cawthorne-cooksey">
            <h3 class="exercise-title"><i class="fa-solid fa-person-walking"></i>3. Cawthorne-Cooksey Exercises</h3>
            <p class="exercise-purpose">Purpose: A structured, progressive vestibular rehabilitation program that trains the brain (vestibular compensation) to rely on vision, neck, and body signals to regain balance, reducing dizziness and unsteadiness over time.</p>

            <div class="exercise-meta-row">
                <span class="exercise-meta-pill"><i class="fa-solid fa-stethoscope"></i> Prescribed for: Vestibular neuritis/labyrinthitis recovery, chronic unsteadiness, post-surgical imbalance, bilateral vestibular weakness</span>
                <span class="exercise-meta-pill"><i class="fa-solid fa-layer-group"></i> Progressive program — advance stages only as tolerated</span>
            </div>

            <p>This program progresses through four stages of increasing difficulty. Only move to the next stage once the current one causes minimal dizziness.</p>

            <div class="cc-progression-tabs">
                <button type="button" class="cc-tab-btn active" data-tab="cc-eye">1. Eye Movements</button>
                <button type="button" class="cc-tab-btn" data-tab="cc-head">2. Head Movements</button>
                <button type="button" class="cc-tab-btn" data-tab="cc-sitting">3. Sitting / Standing</button>
                <button type="button" class="cc-tab-btn" data-tab="cc-walking">4. Walking</button>
            </div>

            <div class="cc-tab-pane active" id="cc-eye-pane">
                <h5 class="exercise-subheading">Stage 1 — Eye Movements (in bed or sitting)</h5>
                <ol class="step-list">
                    <li>Look up, then down slowly, repeat <strong>10 times</strong>.</li>
                    <li>Look from side to side slowly, repeat <strong>10 times</strong>.</li>
                    <li>Focus on a finger held at arm's length, then slowly bring it to about 1 foot from your face, moving it in and out. Repeat <strong>10 times</strong>.</li>
                    <li>Gradually increase the speed of all eye movements as symptoms allow.</li>
                </ol>
            </div>

            <div class="cc-tab-pane" id="cc-head-pane">
                <h5 class="exercise-subheading">Stage 2 — Head Movements (in bed or sitting)</h5>
                <ol class="step-list">
                    <li>Bend your head forward, then backward slowly, eyes open. Repeat <strong>10 times.</strong></li>
                    <li>Turn your head slowly from side to side. Repeat <strong>10 times.</strong></li>
                    <li>Stretch your arms out in front with thumbs pointing upward. Turn your head left and right while keeping your eyes fixed on your thumb. Repeat <strong>10 times.</strong></li>
                    <li>Start slowly, gradually increasing speed once comfortable.</li>
                </ol>
            </div>

            <div class="cc-tab-pane" id="cc-sitting-pane">
                <h5 class="exercise-subheading">Stage 3 — Sitting and Standing</h5>
                <p><strong>Sitting:</strong></p>
                <ol class="step-list">
                    <li>Shrug and circle your shoulders <strong>10 times.</strong></li>
                    <li>Bend forward and pick up objects from the ground in front of you, <strong>5–10 times.</strong></li>
                    <li>Bend side to side and pick up objects from the ground, <strong>5–10 times.</strong></li>
                </ol>
                <p><strong>Standing:</strong></p>
                <ol class="step-list">
                    <li>Repeat the eye, head, and shoulder movements from Stages 1–2 while standing.</li>
                    <li>Change from sitting to standing, first with eyes open, then with eyes closed (only if you are steady and not elderly with low blood pressure on standing — check with the doctor first). Repeat <strong>10 times.</strong></li>
                    <li>Throw a small ball from hand to hand above eye level, <strong>10 times.</strong></li>
                    <li>Throw a small ball from hand to hand under the knee, <strong>10 times.</strong></li>
                    <li>Practice turning around fully while changing from sitting to standing.</li>
                </ol>
            </div>

            <div class="cc-tab-pane" id="cc-walking-pane">
                <h5 class="exercise-subheading">Stage 4 — Walking / Moving About</h5>
                <ol class="step-list">
                    <li>Walk across the room with eyes open, then with eyes closed (with supervision/support nearby), <strong>several times.</strong></li>
                    <li>Walk up and down a gentle slope, <strong>several times.</strong></li>
                    <li>Walk up and down steps holding a rail if needed, <strong>several times.</strong></li>
                    <li>Practice throwing and catching a ball while standing and while walking.</li>
                    <li>Any game/activity involving bending, stretching, and aiming (e.g., light bowling) can be introduced as balance improves.</li>
                </ol>
            </div>

            <div class="freq-box">
                <i class="fa-solid fa-repeat"></i><strong>Frequency:</strong> Practice the current stage 2–3 times daily for 10–20 minutes per session. Most patients need 4–6 weeks of consistent practice to see meaningful improvement — mild dizziness during exercises is expected and usually a sign the brain is adapting.
            </div>

            <div class="warning-box">
                <h5><i class="fa-solid fa-circle-exclamation"></i> STOP and contact the clinic if:</h5>
                <ul>
                    <li>You experience a fall or near-fall during any stage.</li>
                    <li>Dizziness is severe, or symptoms worsen instead of gradually easing over 1–2 weeks.</li>
                    <li>You develop chest pain, palpitations, severe headache, or fainting spells.</li>
                    <li>New weakness, numbness, vision changes, or slurred speech occur.</li>
                    <li>You are unable to progress beyond Stage 1 after several weeks of regular practice — the program may need to be adjusted by the doctor or physiotherapist.</li>
                </ul>
            </div>

