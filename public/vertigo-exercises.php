<!-- Vertigo Exercises Page Logic -->
<script>
(function () {
    "use strict";

    var PAGE_URL = "https://entvaishalisangole.com/vertigo-exercises.php";
    var WHATSAPP_NUMBER = "919967752407";

    // Epley ear toggle
    function initEarToggle() {
        var rightBtn = document.getElementById("epley-right-btn");
        var leftBtn = document.getElementById("epley-left-btn");
        var rightPane = document.getElementById("epley-right-pane");
        var leftPane = document.getElementById("epley-left-pane");

        if (!rightBtn || !leftBtn || !rightPane || !leftPane) return;

        rightBtn.addEventListener("click", function () {
            rightBtn.classList.add("active");
            leftBtn.classList.remove("active");
            rightPane.classList.add("active");
            leftPane.classList.remove("active");
        });

        leftBtn.addEventListener("click", function () {
            leftBtn.classList.add("active");
            rightBtn.classList.remove("active");
            leftPane.classList.add("active");
            rightPane.classList.remove("active");
        });
    }

    // Cawthorne-Cooksey progression tabs
    function initCCTabs() {
        var tabButtons = document.querySelectorAll(".cc-tab-btn");
        if (!tabButtons.length) return;

        tabButtons.forEach(function (btn) {
            btn.addEventListener("click", function () {
                var targetId = btn.getAttribute("data-tab");

                document.querySelectorAll(".cc-tab-btn").forEach(function (b) {
                    b.classList.remove("active");
                });
                document.querySelectorAll(".cc-tab-pane").forEach(function (p) {
                    p.classList.remove("active");
                });

                btn.classList.add("active");
                var pane = document.getElementById(targetId + "-pane");
                if (pane) pane.classList.add("active");
            });
        });
    }

    // WhatsApp share buttons — one per exercise section
    function initWhatsappShare() {
        var shareButtons = document.querySelectorAll(".btn-whatsapp-share-exercise");

        shareButtons.forEach(function (btn) {
            btn.addEventListener("click", function () {
                var exerciseName = btn.getAttribute("data-exercise-name") || "Vertigo Exercise";
                var anchor = btn.getAttribute("data-exercise-anchor") || "";
                var link = PAGE_URL + (anchor ? "#" + anchor : "");

                var message = "*" + exerciseName + "*\n";
                message += "Dr. Vaishali Sangole's ENT & Vertigo Clinic\n\n";
                message += "Here is your prescribed home exercise guide. Please follow the steps only as advised at your visit:\n";
                message += link;

                var encoded = encodeURIComponent(message);
                var whatsappUrl = "https://wa.me/" + WHATSAPP_NUMBER + "?text=" + encoded;
                window.open(whatsappUrl, "_blank");
            });
        });
    }

    document.addEventListener("DOMContentLoaded", function () {
        initEarToggle();
        initCCTabs();
        initWhatsappShare();
    });
})();
</script>

