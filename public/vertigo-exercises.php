            <p class="exercise-purpose">Purpose: A repositioning maneuver used for horizontal (lateral) semicircular canal BPPV, a variant where the classic Epley maneuver is not effective.</p>

            <div class="row align-items-center">
                <div class="col-md-5">
                    <div class="exercise-img-wrap">
                        <img src="images/guffoni-maneuver.jpg" alt="Gufoni maneuver performed in-clinic for horizontal canal BPPV" loading="lazy">
                    </div>
                    <p class="exercise-img-caption">Gufoni maneuver performed in-clinic</p>
                </div>
                <div class="col-md-7">
                    <div class="exercise-meta-row">
                        <span class="exercise-meta-pill"><i class="fa-solid fa-stethoscope"></i> Prescribed for: Horizontal canal BPPV (geotropic or apogeotropic variants)</span>
                    </div>
                    <p>This maneuver involves a rapid sideways movement onto the unaffected/affected side followed by a specific head turn sequence, and is <strong>performed exclusively in-clinic by the doctor</strong> because correct canal identification (via Dix-Hallpike and supine roll test) and precise timing are essential for it to work.</p>
                    <div class="freq-box">
                        <i class="fa-solid fa-repeat"></i><strong>Frequency:</strong> Usually 1–2 sessions in-clinic; the doctor will advise if repeat sessions or a home care routine are needed.
                    </div>
                </div>
            </div>

            <div class="warning-box">
                <h5><i class="fa-solid fa-circle-exclamation"></i> STOP and contact the clinic if:</h5>
                <ul>
                    <li>Vertigo persists or worsens more than 48 hours after the in-clinic maneuver.</li>
                    <li>You develop new hearing loss, severe headache, or neurological symptoms.</li>
                </ul>
            </div>

