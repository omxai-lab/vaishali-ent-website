        <!-- ============ EPLEY MANEUVER ============ -->
        <div class="exercise-card" id="epley">
            <div class="exercise-card-header">
                <div>
                    <h3 class="exercise-title"><i class="fa-solid fa-arrows-spin"></i>1. Epley Maneuver</h3>
                    <p class="exercise-purpose">Purpose: Repositions displaced calcium crystals (otoconia) out of the posterior semicircular canal and back into the utricle, relieving BPPV-related spinning episodes.</p>
                </div>
            </div>

            <div class="exercise-meta-row">
                <span class="exercise-meta-pill"><i class="fa-solid fa-stethoscope"></i> Prescribed for: Benign Paroxysmal Positional Vertigo (BPPV) confirmed on Dix-Hallpike / VNG testing</span>
                <span class="exercise-meta-pill"><i class="fa-solid fa-clock"></i> Each position held: 30–60 seconds, or until vertigo/nystagmus settles</span>
            </div>

            <div class="freq-box">
                <i class="fa-solid fa-repeat"></i><strong>Frequency:</strong> Performed in-clinic first by the doctor. If advised for home repetition, typically once daily for 2–3 days, or as specifically instructed — do not repeat excessively without guidance.
            </div>

            <p>The Epley maneuver differs slightly depending on which ear is affected. Select the variant prescribed to you.</p>

            <div class="ear-toggle-row">
                <button type="button" class="ear-toggle-btn active" id="epley-right-btn" data-ear="right">Right Ear BPPV</button>
                <button type="button" class="ear-toggle-btn" id="epley-left-btn" data-ear="left">Left Ear BPPV</button>
            </div>

            <div class="ear-variant-pane active" id="epley-right-pane">
                <h5 class="exercise-subheading">Steps — Right Ear Variant</h5>
                <ol class="step-list">
                    <li>Sit upright on a bed with legs extended and a pillow positioned so it will sit under your shoulders once you lie back. Turn your head 45° to the <strong>right</strong>.</li>
                    <li>Quickly lie back so your shoulders rest on the pillow and your head (still turned 45° right) tips slightly below the level of the bed. <strong>Hold for 30–60 seconds</strong>, or until any spinning sensation stops.</li>
                    <li>Turn your head 90° to the <strong>left</strong> (now facing 45° to the left) without lifting it up. <strong>Hold for 30–60 seconds.</strong></li>
                    <li>Turn your head and body further onto the left side so you are now looking down at the floor, keeping the head turned with the body. <strong>Hold for 30–60 seconds.</strong></li>
                    <li>Slowly sit up on the left side of the bed, keeping your chin slightly tucked. Remain sitting upright for a few minutes before standing.</li>
                </ol>
            </div>

            <div class="ear-variant-pane" id="epley-left-pane">
                <h5 class="exercise-subheading">Steps — Left Ear Variant (mirror image)</h5>
                <ol class="step-list">
                    <li>Sit upright on a bed with legs extended and a pillow positioned so it will sit under your shoulders once you lie back. Turn your head 45° to the <strong>left</strong>.</li>
                    <li>Quickly lie back so your shoulders rest on the pillow and your head (still turned 45° left) tips slightly below the level of the bed. <strong>Hold for 30–60 seconds</strong>, or until any spinning sensation stops.</li>
                    <li>Turn your head 90° to the <strong>right</strong> (now facing 45° to the right) without lifting it up. <strong>Hold for 30–60 seconds.</strong></li>
                    <li>Turn your head and body further onto the right side so you are now looking down at the floor, keeping the head turned with the body. <strong>Hold for 30–60 seconds.</strong></li>
                    <li>Slowly sit up on the right side of the bed, keeping your chin slightly tucked. Remain sitting upright for a few minutes before standing.</li>
                </ol>
            </div>

            <div class="warning-box">
                <h5><i class="fa-solid fa-circle-exclamation"></i> STOP and contact the clinic if:</h5>
                <ul>
                    <li>Vertigo is more severe, prolonged, or different in character than before starting the maneuver.</li>
                    <li>You experience new double vision, slurred speech, weakness, numbness, or difficulty walking.</li>
                    <li>You develop chest pain, palpitations, or feel you may faint during the maneuver.</li>
                    <li>Symptoms do not improve after the prescribed course, or return within a few days.</li>
                    <li>You have neck or spine problems that make the head/neck positioning painful — inform the doctor before attempting this at home.</li>
                </ul>
            </div>

