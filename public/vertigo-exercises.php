        <!-- ============ BRANDT-DAROFF ============ -->
        <div class="exercise-card" id="brandt-daroff">
            <h3 class="exercise-title"><i class="fa-solid fa-person-falling-burst"></i>2. Brandt-Daroff Exercises</h3>
            <p class="exercise-purpose">Purpose: Habituates the brain to positional signals and helps disperse debris that has settled in the inner ear canals, reducing dizziness with position change. Often used when BPPV keeps recurring or when the exact affected side/canal is unclear.</p>

            <div class="exercise-meta-row">
                <span class="exercise-meta-pill"><i class="fa-solid fa-stethoscope"></i> Prescribed for: Recurrent/multi-canal BPPV, residual dizziness after Epley, or as a home maintenance program</span>
                <span class="exercise-meta-pill"><i class="fa-solid fa-clock"></i> Hold per position: 30 seconds (or until dizziness subsides)</span>
            </div>

            <h5 class="exercise-subheading">Steps (one full repetition)</h5>
            <ol class="step-list">
                <li>Start sitting upright on the edge of your bed with your legs over the side.</li>
                <li>Turn your head 45° to one side, then quickly lie down onto the opposite side (e.g., head turned right, lie down on your left side), keeping your head at the 45° angle. <strong>Hold for 30 seconds</strong>, or until any dizziness fades.</li>
                <li>Sit back up to the starting position and <strong>hold for 30 seconds.</strong></li>
                <li>Turn your head 45° to the other side, then quickly lie down onto the opposite side (head turned left, lie down on your right side). <strong>Hold for 30 seconds.</strong></li>
                <li>Sit back up to the starting position. This completes one full repetition.</li>
            </ol>

            <div class="freq-box">
                <i class="fa-solid fa-repeat"></i><strong>Frequency:</strong> 3 sets of 5 repetitions, 2–3 times daily, for approximately 2 weeks or until symptom-free for 2 consecutive days — or as advised by the doctor.
            </div>

            <div class="warning-box">
                <h5><i class="fa-solid fa-circle-exclamation"></i> STOP and contact the clinic if:</h5>
                <ul>
                    <li>Dizziness worsens progressively over several days instead of improving.</li>
                    <li>You experience nausea/vomiting severe enough to prevent completing the exercises — ask about anti-vertigo medication cover.</li>
                    <li>New neurological symptoms appear (vision changes, weakness, slurred speech, numbness).</li>
                    <li>You feel unsteady enough to be at risk of falling while getting up from bed.</li>
                    <li>No improvement is seen after 2 weeks of consistent practice.</li>
                </ul>
            </div>

            <button type="button" class="btn-whatsapp-share-exercise" data-exercise-name="Brandt-Daroff Exercises" data-exercise-anchor="brandt-daroff">
