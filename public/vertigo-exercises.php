            <h3 class="exercise-title"><i class="fa-solid fa-hospital-user"></i>5. Yacovino Maneuver</h3>
            <p class="exercise-purpose">Purpose: A repositioning maneuver specifically designed for BPPV affecting the anterior (superior) semicircular canal — the least common canal involved in BPPV.</p>

            <div class="row align-items-center">
                <div class="col-md-5">
                    <div class="exercise-img-wrap">
                        <img src="images/yacovino-maneuver.jpg" alt="Yacovino maneuver performed in-clinic for anterior canal BPPV" loading="lazy">
                    </div>
                    <p class="exercise-img-caption">Yacovino maneuver performed in-clinic</p>
                </div>
                <div class="col-md-7">
                    <div class="exercise-meta-row">
                        <span class="exercise-meta-pill"><i class="fa-solid fa-stethoscope"></i> Prescribed for: Anterior/superior semicircular canal BPPV</span>
                    </div>
                    <p>The maneuver takes the patient through a deep head-hanging position followed by a controlled return to sitting, moving debris out of the anterior canal. Because this canal is less commonly involved and the deep-hang position needs care (especially in patients with neck or cardiovascular conditions), this maneuver is <strong>performed exclusively in-clinic under the doctor's supervision</strong>.</p>
                    <div class="freq-box">
                        <i class="fa-solid fa-repeat"></i><strong>Frequency:</strong> Usually 1–2 sessions in-clinic; repeat sessions only if advised after clinical review.
                    </div>
                </div>
            </div>

            <div class="warning-box">
                <h5><i class="fa-solid fa-circle-exclamation"></i> STOP and contact the clinic if:</h5>
                <ul>
                    <li>Vertigo persists or worsens more than 48 hours after the in-clinic maneuver.</li>
                    <li>You experience neck pain, palpitations, or breathlessness during/after the procedure.</li>
                    <li>New neurological symptoms develop.</li>
                </ul>
