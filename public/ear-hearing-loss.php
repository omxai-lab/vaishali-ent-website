                                    <h6>What Is Hearing Loss?</h6>

                                    <p>Hearing loss is when you are unable to partially or completely hear sound in one or both of your ears. In most people, hearing loss begins after age 20 (MedlinePlus). Hearing loss typically occurs gradually over time, but by the time a person reaches 65, hearing loss can be quite significant. The National Institute on Deafness and Other Communication Disorders (NICDC) reported that, in 2010, 30 percent of those between the ages of 65 and 74 said they had hearing loss (NICDC).</p>

                                </div>

                                <div class="ser-info-wrap full">

                                    <h6>Hearing loss is also known as:</h6>

                                    <ul class="list-group-borderless">

                                        <li><i class="fa fa-check"></i> decreased hearing</li>

                                        <li><i class="fa fa-check"></i> deafness</li>

                                        <li><i class="fa fa-check"></i> loss of hearing</li>

                                        <li><i class="fa fa-check"></i> conductive hearing loss</li>

                                    </ul>

                                    <h6>How Hearing Works</h6>

                                    <p>There are three main parts to the ear: the outer ear, middle ear, and inner ear. The hearing process includes these basic steps.</p>

                                    <ul class="list-group-borderless">

                                        <li><i class="fa fa-check"></i> Hearing begins when sound waves pass through the outer ear to the eardrum (a thin piece of skin between your outer and middle ear).</li>

                                        <li><i class="fa fa-check"></i> When the sound waves reach the eardrum, the eardrum vibrates.</li>

                                        <li><i class="fa fa-check"></i> The eardrum and the three bones of the middle ear (the hammer, anvil, and stirrup, together called the ossicles) then work together to increase the vibrations as the sound waves travel onward to the inner ear.</li>

                                        <li><i class="fa fa-check"></i> When the sound waves reach the inner ear, they travel through the fluids of the cochlea. The cochlea is an inner-ear structure sometimes described as being snail-shaped (Mayo, 2011).</li>

                                        <li><i class="fa fa-check"></i> In the cochlea are nerve cells with thousands of mini hairs attached to them. These hairs help to convert the sound wave vibrations into electrical signals that are then communicated to your brain.</li>

                                        <li><i class="fa fa-check"></i> Your brain then interprets these electrical signals as sound. Different sound vibrations create different reactions in these tiny hairs; thereby signaling different sounds to your brain.</li>

                                    </ul>

                                    <h6>What Are the Common Underlying Causes of Hearing Loss?</h6>

                                    <p>The American Speech-Language-Hearing Association (ASHA) reports that there are three basic types of hearing loss, each caused by different underlying factors. The three most common causes of decreased hearing include conductive hearing loss, sensorineural hearing loss (SNHL), and mixed hearing loss (ASHA).</p>

                                    <h6>Conductive Hearing Loss</h6>

                                    <p>This type of hearing loss occurs when sounds are not able to travel from the outer ear to the eardrum and the bones of the middle ear. When this type of hearing loss occurs, you may find it difficult to hear soft or muffled sounds. Conductive hearing loss can be treated through medical interventions and is not always permanent. Treatment may include antibiotics or surgical interventions, such as a cochlear implant. A cochlear implant is a small electrical machine (placed under your skin behind the ear) that translates sound vibrations into electrical signals that your brain can then interpret as meaningful sound.</p>

                                    <h6>Conductive hearing loss can be caused by:</h6>

                                    <ul class="list-group-borderless">

                                        <li><i class="fa fa-check"></i> ear infections (otitis media)</li>

                                        <li><i class="fa fa-check"></i> allergies (serous otitis media)</li>

                                        <li><i class="fa fa-check"></i> swimmer’s ear (otitis externa)</li>

                                        <li><i class="fa fa-check"></i> a buildup of wax in the ear</li>

                                        <li><i class="fa fa-check"></i> a foreign object that has become stuck in the ear</li>

                                        <li><i class="fa fa-check"></i> benign tumors</li>

                                        <li><i class="fa fa-check"></i> scarring of the ear canal due to recurrent infections</li>

                                    </ul>

                                    <h6>Sensorineural Hearing Loss (SNHL)</h6>

                                    <p>This type of hearing loss happens when there is damage to inner ear structures or in the nerve pathways to the brain. This type of hearing loss is usually permanent. SNHL makes even distinct, normal-to-loud sounds seem muffled or unclear.</p>

                                    <ul class="list-group-borderless">

                                        <li><i class="fa fa-check"></i> birth defects that alter the structure of the ear</li>

                                        <li><i class="fa fa-check"></i> aging</li>

                                        <li><i class="fa fa-check"></i> working around loud noises</li>

                                        <li><i class="fa fa-check"></i> trauma to the head or skull</li>

                                        <li><i class="fa fa-check"></i> infections that damaged the nerves of the ear, such as measles, meningitis, mumps, or scarlet fever</li>

                                        <li><i class="fa fa-check"></i> acoustic neuroma (a noncancerous tumor that grows on the nerve that connects the ear to the brain, known as the vestibular cochlear nerve)</li>

                                        <li><i class="fa fa-check"></i> Meniere’s disease (a disorder of the inner ear that can affect hearing and balance)</li>

                                    </ul>



                                    <p>Some medications, called ototoxic medications, may also cause SNHL. According to the American Speech-Language-Hearing Association, there are over 200 medications (over-the-counter and prescription) that may cause hearing loss. If you are taking medications for cancer, heart disease, or a serious infection, talk with your doctor about the hearing risks involved with each (ASHA).

                                    </p>



