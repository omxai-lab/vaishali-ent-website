                                    <h6>What Is Noise-Induced Hearing Loss /Acoustic Trauma?</h6>

                                    <p>Acoustic trauma is an injury to the inner ear that is often caused by exposure to a high decibel noise. This injury

                                        can be related to a single very loud noise or by exposure to a lower decibel noise over a long period of time. Some

                                        injuries to the head can cause acoustic trauma if the eardrum is ruptured, or if other injuries to the inner ear

                                        occur.



                                        The eardrum protects the middle and inner ear. It also transmits signals to the brain by way of small vibrations.

                                        Acoustic trauma can damage the way that these vibrations are handled, causing hearing loss. Sound moving into the

                                        inner ear can cause what doctors sometimes call a “threshold shift,” which can trigger hearing loss.

                                    </p>



                                    <h6>Types of Noise-Induced Hearing Loss.</h6>

                                    <p>If your doctor believes that your symptoms indicate acoustic trauma, he or she may try to differentiate between

                                        trauma that occurred through injury and trauma that occurred through exposure to loud noises. Different degrees of

                                        acoustic trauma can also require different treatments.</p>



                                    <h6>Who Is at High Risk for Noise-Induced Hearing Loss /Acoustic Trauma?</h6>

                                    <p>Those who experience the following types of situations are at a higher risk for acoustic trauma:</p>

                                    <ul class="list-group-borderless">

                                        <li><i class="fa fa-check"></i> those who work at a job where loud industrial equipment operates for long periods of time</li>

                                        <li><i class="fa fa-check"></i> those who live or work where other high-decibel sounds continue for long periods of time</li>

                                        <li><i class="fa fa-check"></i> individuals who frequently attend music concerts and other events with high-decibel music</li>

                                        <li><i class="fa fa-check"></i> those who use gun ranges</li>

                                        <li><i class="fa fa-check"></i> people who experience gun reports or other extremely loud sounds without proper equipment, such as

                                            earplugs</li>

                                    </ul>



                                    <p>In terms of specific risks, those exposed to over 85 decibels of sound continually are at a higher risk for

                                        acoustic trauma. Your doctor may provide an estimate of the decibel range of normal daily sounds, such as an

                                        estimate of around 90 decibels for a small engine, in order to help you assess whether the sounds that you encounter

                                        put you at a higher risk for acoustic trauma and hearing loss.</p>



                                    <h6>Symptoms of Noise-Induced Hearing Loss /Acoustic Trauma</h6>

                                    <p>The main symptom of acoustic trauma is hearing loss. Experts point out that, in many cases, patients first begin to

                                        experience difficulty hearing high-frequency sounds. The trouble with sounds at lower frequencies may occur later.

                                        Doctors may test response to different frequencies of sound to assess the extent of acoustic trauma.



                                        One of the most important symptoms that can signal the onset of acoustic trauma is called tinnitus. Tinnitus is a

                                        type of injury to the ear that causes a buzzing or ringing sound. Those with slight to moderate tinnitus will most

                                        often be aware of this symptom when they are in a silent environment. While tinnitus can be caused by drug use,

                                        changes to blood vessels, or other factors, it is often a precursor to acoustic trauma when it is caused by exposure

                                        to loud noises. Tinnitus can be persistent or chronic, where long-term tinnitus is a good reason to suspect acoustic

                                        trauma.</p>



                                    <h6>Diagnosing Noise-Induced Hearing Loss /Acoustic Trauma</h6>

                                    <p>To diagnose acoustic trauma, your doctor will ask you what kind of noises you have been exposed to during different

                                        times of your life. Doctors may also use something called audiometry to detect signs of acoustic trauma. This kind

                                        of test involves providing sounds of various loudness and different tones in order to more carefully assess what the

                                        patient can and can’t hear.</p>





                                    <h6>Treating Noise-Induced Hearing Loss /Acoustic Trauma</h6>

                                    <h6>Technical Hearing Assistance</h6>

                                    <p>While hearing loss can be treated, it cannot be cured. Your doctor may recommend technological assistance for your

                                        hearing loss condition, such as a hearing aid. New types of hearing aids called cochlear implants may also be

                                        available to help you deal with hearing loss from acoustic trauma.</p>



                                    <h6>Ear Protection</h6>

                                    <p>Your doctor will most likely recommend using earplugs and other kinds of hearing protection devices. These items,

                                        when applied to a workplace scenario, are part of the PPE (personal protective equipment) that employers should

                                        offer to workers.</p>



                                    <h6>Medications</h6>

                                    <p>In some cases, oral steroid medications may be prescribed to help with acoustic trauma. However, if you are

                                        experiencing hearing loss, your doctor will stress protection of the ear in order to prevent the problem from

                                        getting worse.</p>



                                    <h6>Prognosis for Noise-Induced Hearing Loss /Acoustic Trauma</h6>

                                    <p>Acoustic trauma and related hearing loss cannot be reversed. Some patients are able to keep the remaining portion

                                        of their hearing capacity by protecting their ears from loud noises. In some extreme cases, doctors will recommend

                                        learning sign language in order to allow for communications if hearing loss becomes considerable.</p>







                                    <h6>What Is Sudden Sensorineural Hearing Loss?</h6>

                                    <p>When you lose your hearing very quickly, it is called sudden sensorineural hearing loss (SSHL). It can happen

                                        instantly or over a span of several days, during which sound is gradually muffled or reduced. This type of hearing

                                        loss typically affects one ear.



                                        Decibels measure the intensity of the sounds we hear. Frequencies measure sound waves. Losing 30 decibels in three

                                        connected frequencies is considered SSHL. There are about 4,000 cases of SSHL every year in the United States, most

                                        commonly among people aged 30 to 60.



                                        Early treatment for SSHL can save your hearing. Most people recover, but about 15 percent have hearing loss that

                                        continues to worsen. Advances in hearing aid technology and cochlear implants are helping to improve communication

                                        for people affected by hearing loss.



                                        SSHL is a medical emergency and requires immediate attention.</p>





                                    <h6>Causes of SSHL</h6>

                                    <p>SSHL happens when the inner ear or the nerve pathways between the ear and the brain become damaged.



                                        Only about 10 to 15 percent of people with SSHL ever know what actually caused their hearing loss. That may be

                                        because there are more than 100 possible causes, including:</p>

                                    <div class="row">

                                        <div class="col-md-6">

                                            <ul class="list-group-borderless">

                                                <li><i class="fa fa-check"></i> malformation of the inner ear</li>

                                                <li><i class="fa fa-check"></i> head injury or trauma</li>

                                                <li><i class="fa fa-check"></i> loud-noise exposure</li>

                                                <li><i class="fa fa-check"></i> neurologic conditions</li>

                                                <li><i class="fa fa-check"></i> immune system diseases</li>

                                                <li><i class="fa fa-check"></i> Ménière’s disease</li>

                                                <li><i class="fa fa-check"></i> Lyme disease</li>

                                            </ul>

                                        </div>

                                        <div class="col-md-6">

                                            <ul class="list-group-borderless">

                                                <li><i class="fa fa-check"></i> infectious diseases</li>

                                                <li><i class="fa fa-check"></i> medications that can harm the ear</li>

                                                <li><i class="fa fa-check"></i> snake bite or other toxic event</li>

                                                <li><i class="fa fa-check"></i> circulatory problems</li>

                                                <li><i class="fa fa-check"></i> abnormal tissue growth or tumors</li>

                                                <li><i class="fa fa-check"></i> disease of the blood vessels</li>

                                                <li><i class="fa fa-check"></i> aging</li>

                                            </ul>

                                        </div>

                                    </div>

                                    <h6>Congenital SSHL</h6>

                                    <p>Infants can be born with SSHL for a variety of reasons including:

                                    </p>

                            <ul class="list-group-borderless">

                                <li><i class="fa fa-check"></i> infections that pass from the mother (such as rubella, syphilis, and herpes)</li>

                                <li><i class="fa fa-check"></i> Toxoplasma gondii (a parasite that passes through the womb)</li>

                                <li><i class="fa fa-check"></i> individuals who frequently attend music concerts and other events with high-decibel

                                    music</li>

                                <li><i class="fa fa-check"></i> genetic factors</li>

                                <li><i class="fa fa-check"></i> low birth weight</li>

                            </ul>

                            <h6>Tests for Hearing Loss</h6>

                            <p>Your doctor will take a medical history and conduct a physical exam. You will be asked about other medical

                                conditions and about what over-the-counter and prescription medications you take.



                                You may be asked to cover one ear at a time while listening to sounds at different volumes. Tests using a tuning

                                fork can check if there is damage to the parts of the middle ear and eardrum that vibrate.



                                Your hearing can be more thoroughly checked with audiometer tests. An audiologist can conduct thorough testing of

                                your hearing ability using earphones. Different sounds and levels can be sent to each ear individually. A series of

                                sounds at different volumes can help find the level where your hearing fades.



                                Additional testing for a cause of a sudden sensorineural hearing loss should include an MRI (magnetic resonance

                                imaging) scan looking for an acoustic neuroma (tumor of the nerve).</p>



                            <h6>When to Test Your Child’s Hearing</h6>

                            <p>Hearing loss could develop as a result of infections at birth, use of a ventilator, or certain medications known as

                                ototoxic medications. It may not always be easy to know if your child is hearing correctly. You should have your

                                child’s hearing tested if he or she:</p>

                            <ul class="list-group-borderless">

                                <li><i class="fa fa-check"></i> doesn’t seem to understand a language</li>

                                <li><i class="fa fa-check"></i> doesn’t attempt to form words</li>

                                <li><i class="fa fa-check"></i> has had many ear infections or problems with middle-ear fluid</li>

                                <li><i class="fa fa-check"></i> doesn’t seem to startle at sudden noises or respond to sounds as you would expect

                                </li>

                            </ul>



                            <h6>Symptoms of SSHL</h6>

                            <p>Hearing loss may be noticed upon awakening in the morning. Some people become aware of it when they use earphones

                                or hold a phone to the deaf ear. Hearing loss is sometimes preceded by a loud popping sound.</p>

                            <p>Other signs include:</p>

                            <ul class="list-group-borderless">

                                <li><i class="fa fa-check"></i> trouble following group conversations</li>

                                <li><i class="fa fa-check"></i> muffled conversation sounds</li>

                                <li><i class="fa fa-check"></i> experiencing sounds that feel too loud</li>

                                <li><i class="fa fa-check"></i> inability to hear well when there’s a lot of background noise</li>

                                <li><i class="fa fa-check"></i> more trouble hearing women’s voices than men’s</li>

                                <li><i class="fa fa-check"></i> difficulty hearing high-pitched sounds</li>

                                <li><i class="fa fa-check"></i> experiencing dizziness or balance problems</li>

                                <li><i class="fa fa-check"></i> tinnitus (hearing ringing or buzzing sounds)</li>

                            </ul>

                            <p>Hearing loss affects only one ear for nine out of 10 people with SSHL.</p>





                            <h6>Treatment for SSHL</h6>

                            <p>Early treatment may help your chances for a full recovery. However, the doctor will try to identify the cause of

                                your hearing loss before treatment can begin.



                                The most common treatment involves the use of steroids. Steroids can reduce inflammation and swelling. This may be

                                especially helpful in patients who have diseases of the immune system.



                                Hearing aids and telephone amplifiers can help if your hearing does not improve. Sign language and lip reading can

                                improve communication for people with severe hearing loss.



                                A cochlear implant can be surgically put in place. This implant doesn’t restore hearing to normal, but it can

                                amplify sounds to a more normal level.



                                    </p>





                            <h6>Outlook for SSHL</h6>



                            <p>For some people, SSHL improves on its own without any medical intervention. Usually, this happens in the first few

                                days after hearing loss. This is called a spontaneous recovery. Others recover their hearing more slowly, usually

                                within a week or two.



                                Fifteen percent of people who experience SSHL do not recover, but continue to lose their hearing in time.</p>



