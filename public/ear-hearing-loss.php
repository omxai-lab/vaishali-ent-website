                                    <ul class="list-group-borderless">

                                        <li><i class="fa fa-check"></i> hearing loss that interferes with your daily activities</li>

                                        <li><i class="fa fa-check"></i> hearing loss that interferes with your daily activities</li>

                                        <li><i class="fa fa-check"></i> hearing loss that is worse in one ear</li>

