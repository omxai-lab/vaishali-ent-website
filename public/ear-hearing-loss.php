                                        <li><i class="fa fa-check"></i> having ear pain along with hearing problems</li>

                                        <li><i class="fa fa-check"></i> ringing in the ear</li>

                                        <li><i class="fa fa-check"></i> severe hearing loss</li>

                                        <li><i class="fa fa-check"></i> headaches, numbness, or weakness</li>

                                    </ul>

                                    <p>If you experience headaches, numbness or weakness, coupled with chills, quick breathing, neck stiffness, vomiting,

                                        sensitivity to light, or mental agitation, you should seek emergency medical treatment. These symptoms may be

                                        associated with life-threatening conditions, such as meningitis, that warrant immediate medical attention.</p>

                                    <h6>How Can the Symptoms of Hearing Loss Be Treated?</h6>

                                    <p>If you develop hearing loss that is due to a buildup of wax in the ear canal, you can remove the wax at home.

                                        Over-the-counter solutions, including wax softeners, can be used to remove wax from the ear. Syringes can also be

                                        used to push warm water through the ear canal to remove the wax. If a foreign object is stuck in the ear canal, you

                                        may (depending on the object) be able to remove the object at home. However, in this case, it would be wise to

                                        consult your doctor before attempting to remove the object—you do not want to unintentionally damage your ear.

                                        For other causes of hearing loss, you will need to see your doctor. If your hearing loss is caused by an infection,

                                        your doctor may need to prescribe antibiotics. If your hearing loss is caused by other conductive hearing problems,

                                        your doctor may refer you to a specialist to receive a hearing aid or a cochlear implant.</p>

                                    <h6>What Are the Complications of Hearing Loss?</h6>

                                    <p>Hearing loss has been shown to negatively impact a person’s quality of life and mental state. If you develop

                                        hearing loss, you may have difficulty understanding others. This can increase your anxiety level or cause

                                        depression. Treatment for hearing loss may improve your life significantly. It may restore self-confidence while

                                        also improving your ability to communicate with friends and family members.</p>



                                    <h6> How Can You Prevent Hearing Loss?</h6>

                                    <p>Not all cases of hearing loss can be prevented. However, there are several steps that you can take to protect your

                                        hearing:</p>

                                    <ul class="list-group-borderless">

                                        <li><i class="fa fa-check"></i> Use safety equipment if you work in areas with loud noises, and wear earplugs when you swim and go to

                                            concerts. Statistics from 2010 showed that 15 percent of individuals ages 20 to 69 experienced hearing loss due to

                                            loud noise (NIDCD).</li>

                                        <li><i class="fa fa-check"></i> Have regular hearing tests if you work around loud noises, swim often, or go to concerts on a regular

                                            basis.</li>

                                        <li><i class="fa fa-check"></i> Avoid prolonged exposure to loud noises and music.</li>

                                        <li><i class="fa fa-check"></i> Avoid prolonged use of noisy surroundings like the industrial nose.</li>

                                        <li><i class="fa fa-check"></i> Avoid exposure to high-frequency noises like engines, ammunition, and motorbikes.</li>

                                        <li><i class="fa fa-check"></i> Avoid smoking as it hastens the hearing loss process.</li>

                                        <li><i class="fa fa-check"></i> Seek help for ear infections, as they may cause permanent damage to the ear if left untreated.</li>

                                    </ul>

