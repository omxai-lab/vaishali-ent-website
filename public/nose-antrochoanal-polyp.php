                                    <h6>What is Antrochoanal nasal polyp?</h6>

                                    <p>An antrochoanal nasal polyp is a prolapsed, pedunculated, painless, pearly white oedematous nasal mucosa, lining the nose and maxillary sinuses.</p>

                                    <h6>What is the incidence of antrochoanal nasal polyp?</h6>

                                    <ul class="list-group-borderless">

                                        <li><i class="fa fa-check"></i> Age: Antrochoanal nasal polyp is common in children</li>

                                        <li><i class="fa fa-check"></i> Sex: Males are more affected than females</li>

