                                    <h6>What are the causes of antrochoanal nasal polyp?</h6>

                                    <ul class="list-group-borderless">

                                        <li><i class="fa fa-check"></i> Infection: Antrochoanal polyps have infective etiology</li>

                                        <li><i class="fa fa-check"></i> Other theories:</li>

                                        <li><i class="fa fa-check"></i> Bernoulli’s phenomenon due to negative pressure</li>

                                        <li><i class="fa fa-check"></i> Polysaccharide changes of ground substance</li>

                                        <li><i class="fa fa-check"></i> Vasomotor imbalance</li>

                                    </ul>

                                </div>

                                <div class="ser-info-wrap full">

                                    <h6>What is the pathology of antrochoanal nasal polyp?</h6>

                                    <p>The polyp can extend into the nasopharynx and oropharynx as it enlarges. It has an antral part, a choanal part, and a nasal part. The choanal part of the largest.</p>

                                    <h6>What are the symptoms of antrochoanal nasal polyp?</h6>

                                    <ul class="list-group-borderless">

                                        <li><i class="fa fa-check"></i> Nasal obstruction: It is usually unilateral not relieved by nasal decongestant drops.</li>

                                        <li><i class="fa fa-check"></i> Nasal discharge: It is unilateral, mucupurulent and occasionally blood tinged.</li>

                                        <li><i class="fa fa-check"></i> Post nasal drip: It is present and mucopurulent in nature.</li>

                                        <li><i class="fa fa-check"></i> Many patients come to the specialist with a chronic cold, quite unaware that they may be having an antochoanal polyp</li>

                                        <li><i class="fa fa-check"></i> Rhinolalia clausa: Present due to nasal obstruction.</li>

                                        <li><i class="fa fa-check"></i> Broadening of the nasal bridge.</li>

                                    </ul>

                                </div>

                            </li>

