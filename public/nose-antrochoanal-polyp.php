                                    <h6>What investigations are required to be done for antrochoanal nasal polyp?</h6>

                                    <ul class="list-group-borderless">

                                        <li><i class="fa fa-check"></i> X-ray of Paranasal Sinuses: This will show the extent of the disease in the sinuses. A polyp is seen as a soft tissue shadow in maxillary sinus with convexity upwards.</li>

                                        <li><i class="fa fa-check"></i> CT Scan of the Paranasal Sinuses: This is the investigation of choice, prior to surgery. CT Scan reveals the extent of the disease, orbital involvement, vascularity, and also altered anatomy in previously operated patients.



                                        </li>

                                    </ul>

                                </div>

                                <div class="ser-info-wrap full">

                                    <h6>What is the treatment of Antrochoanal nasal polyp?</h6>

                                    

                                    <ul class="list-group-borderless">

                                        <li><i class="fa fa-check"></i> Medical Treatment: Not much use in an antrochoanal polyp. Antibiotics, decongestants, analgesics can be used along with surgical treatment.</li>

                                        <li><i class="fa fa-check"></i> Surgical Treatment: Functional Endoscopic Sinus Surgery (FESS). It is the treatment of choice and can be done along with microdebrider.</li>

                                        <li><i class="fa fa-check"></i> Caldwell Luc Surgery: Rarely done nowadays. Performed only for recurrent anthro-choanal polyposis.</li>

