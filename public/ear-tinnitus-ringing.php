                                        dull the ringing, buzzing, or roaring by providing relaxing noises to mask your ear sounds. You might also try a

                                        masking device, similar to a hearing aid, which you insert into your ear.



                                        Hearing aids can be beneficial for some people with tinnitus. Sound amplification can help those who have trouble

                                        hearing “normal” noises due to their tinnitus. Cochlear implants to restore lost hearing may also be effective.



                                        A cochlear implant is a device that allows your brain to bypass the damaged part of your ear to help you hear more

                                        effectively. A microphone implanted just above your ear works with an electrode inserted into your inner ear. The

                                        implant sends your auditory nerves the signals you need to process sound. Cochlear implants and other forms of

                                        electrical stimulation can help your brain interpret sounds properly.



                                        You can also take steps to manage your tinnitus by reducing stress. Stress does not cause tinnitus, but can make it

                                        worse. Engage in a hobby or talk with a trusted friend or family member to reduce stress in your life.



                                        You should also avoid exposure to loud noises to lessen the severity of your tinnitus.</p>



                                    <h6>Preventing Tinnitus</h6>

                                    <p>Protect your ears from loud noises to help prevent tinnitus. Keep a close eye on the volume levels of your television,

                                        radio, and personal music player. Wear ear protection around noises louder than 85 decibels—the level associated with

                                        average traffic noise. If proper ear protection, such as earplugs, is not available, cover your ears when surrounded

                                        by loud music or construction noise.



                                        Avoid medications that may cause your tinnitus symptoms to recur, and schedule regular hearing tests with your doctor

                                        to promptly detect any problems with the structure of your inner and middle ear.</p>

