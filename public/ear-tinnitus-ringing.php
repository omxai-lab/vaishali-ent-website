                                    <h6>Causes of Tinnitus</h6>

                                    <p>Damage to the middle or inner ear is a common cause of tinnitus. Your middle ear picks up sound waves and prompts your inner ear to transmit electrical impulses to your brain. Only after your brain accepts these signals and translates them into sounds are you able to hear them. Sometimes, your inner ear becomes damaged, altering the way your brain processes sound. Damage to your eardrums or to the tiny bones in your middle ear can also interfere with the proper conduction of sound. Tumors in the ear or on the auditory nerve may also cause ringing in the ears. Exposure to very loud sounds on a regular basis can cause tinnitus in some people. Those who work in construction or in other fields utilizing jackhammers, chain saws, or other heavy equipment are more likely to suffer from tinnitus. Listening to loud music through headphones or at a concert may also produce temporary symptoms of tinnitus.</p>

