                                    <h6>Treating Tinnitus</h6>



                                    <p>Your doctor will treat any underlying medical conditions causing your tinnitus. Blood vessel abnormalities will be

                                        corrected, and excess earwax can be removed. If medications are contributing to your tinnitus, your doctor may

                                        switch your prescriptions in an effort to restore normal hearing.



                                        Drug therapy can also be effective in reducing the sounds you hear in your ears.

