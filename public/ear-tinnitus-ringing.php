                                    <h6>WHAT IS TINNITUS?</h6>

                                    <p>Tinnitus is the medical term for noises in the ears. Most people refer to tinnitus as “ringing in the ears.” The feedback you hear, however, is not limited to ringing. You may also hear roaring, buzzing, whistle, or hissing if you suffer from tinnitus. Although you hear sounds in your ears, there is no external sound source. This means there is nothing close to your head that makes the sounds you hear. For this reason, the sounds of tinnitus are sometimes called “phantom sounds.” Tinnitus can be annoying and frustrating. Sometimes, the sounds you hear can interfere with hearing real sounds around you. Tinnitus is linked to depression, anxiety, and stress. </p>

                                </div>

                                <div class="ser-info-wrap full">

                                    <p>You may experience tinnitus in one or both ears. People of all ages can develop tinnitus, but it is more common in older adults. There are two forms of tinnitus: objective and subjective. Objective tinnitus means that both you and other people can hear certain noises in your ears. This is usually due to abnormal blood vessels in and around your ears. When your heart beats, you and others can hear a distinct pulsing sound. Objective tinnitus is rare, while subjective tinnitus is much more common. Only you can hear the roaring, ringing, and other sounds of subjective tinnitus.</p>

